# ❶ 정수문자열→정수 변환 후 연산 (실수입력은 오류)

x = int(input("숫자1: "))
y = int(input("숫자2: "))

print(f"덧셈: {x} + {y} = {x + y}")
print(f"뺄셈: {x} - {y} = {x - y}")
print(f"곱셈: {x} * {y} = {x * y}")
print(f"나눗셈: {x} / {y} = {x / y}")
print(f"몫: {x} // {y} = {x // y}")
print(f"나머지: {x} % {y} = {x % y}")
print(f"거듭제곱: {x} ** {y} = {x ** y}")