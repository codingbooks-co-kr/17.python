# ❶ 변수 기반 두 수의 다양한 연산

x = 10			# 입력1
y = 3			# 입력2

total = x + y		# 계산1
sub = x - y		# 계산2
mul = x * y		# 계산3
div = x / y		# 계산4
quo =  x // y		# 계산5
rem = x % y		# 계산6
power = x ** y		# 계산7

print("덧셈:", total)		# 결과1
print("뺄셈:", sub)		# 결과2
print("곱셈:", mul)		# 결과3
print("나눗셈:", div)		# 결과4
print("몫:", quo)		# 결과5
print("나머지:", rem)		# 결과6
print("거듭제곱:", power)	# 결과7