# ❷ 변수 기반 두 수의 다양한 연산

x = 10			# 입력1
y = 3			# 입력2

result = x + y		# 계산
print("덧셈:", result)		# 결과

result = x - y		# 계산
print("뺄셈:", result)		# 결과

result = x * y		# 계산
print("곱셈:", result)		# 결과

result = x / y		# 계산
print("나눗셈:", result)	# 결과

result = x // y		# 계산
print("몫:", result)		# 결과

result = x % y		# 계산
print("나머지:", result)	# 결과

result = x ** y		# 계산
print("거듭제곱:", result)	# 결과