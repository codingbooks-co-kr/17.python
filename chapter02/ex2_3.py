# 복합 할당 연산자 기반 두 수의 다양한 연산

num = 10
num += 3	# num = num + 3
print("덧셈할당:", num)

num = 10
num -= 3	# num = num - 3
print("뺄셈할당:", num)

num = 10
num *= 3		# num = num * 3
print("곱셈할당:", num)

num = 10
num /= 3		# num = num / 3
print("나눗셈할당:", num)

num = 10
num //= 3	# num = num // 3
print("몫할당:", num)

num = 10
num %= 3	# num = num % 3
print("나머지할당:", num)

num = 10
num **= 3	# num = num ** 3
print("거듭제곱할당:", num)