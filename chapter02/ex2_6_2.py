# ❷ 숫자문자열→실수 변환 후 연산

x = float(input("숫자1: "))
y = float(input("숫자2: "))

print(f"덧셈: {x} + {y} = {x + y}")
print(f"뺄셈: {x} - {y} = {x - y}")
print(f"곱셈: {x} * {y} = {x * y}")
print(f"나눗셈: {x} / {y} = {x / y:.1f}")
print(f"몫: {x} // {y} = {x // y}")
print(f"나머지: {x} % {y} = {x % y}")
print(f"거듭제곱: {x} ** {y} = {x ** y}")