# 숫자 리스트 관련 다양한 내장 함수
nums = [1, 3, 5 ,4, 2]
print(len(nums))		# 리스트의 길이 반환
print(min(nums))		# 가장 작은 유니코드값의 요소 반환
print(max(nums))		# 가장 큰 유니코드값의 요소 반환
print(sorted(nums))		# 리스트의 요소를 오름차순 정렬, 반환
print(sum(nums))		# 리스트 모든 요소의 합계 값 반환 

# 문자열 리스트 관련 다양한 내장 함수
fruits = ["사과", "딸기", "수박", "포도"]
print(len(fruits))		# 리스트의 길이 반환
print(min(fruits))		# 가장 작은 유니코드값의 문자 반환
print(max(fruits))		# 가장 큰 유니코드값의 문자 반환
print(sorted(fruits))		# 문자열의 요소를 오름차순 정렬, 반환